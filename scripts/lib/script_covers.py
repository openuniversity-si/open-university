"""The covers map of the script tests (GX-08, D-070; D-322): one manifest per test, <gate-tests.covers_dir>/<test>.json
({script, covers}), the selector files of gate-tests.fallback and the traced map, read on demand.

A layer-0 reader (engine-config): it imports nothing of the engine but the registry, so a check of a lower layer
(the known-defect router and detector) reads the map without importing the gate. gate_script_tests, the gate's
selection, re-exports every name here for its own callers. A `modules` field left in a manifest is read as nothing
(VAZÃO F57): no script test installs a package.
"""
import json
from pathlib import Path
import subprocess

import config

ROOT = Path(__file__).resolve().parent.parent.parent
# The registry is read from the checkout this module lives in, never from the tool root's config.py (the gate runs the head's code under the base tip's tooling).
SUFFIX = '.test.sh'
MANIFEST_SUFFIX = '.json'


class ScriptTestMapError(ValueError):
    pass


def discover(root=ROOT):
    directory = Path(root) / 'scripts' / 'tests'
    return tuple(sorted(path.relative_to(root).as_posix() for path in directory.glob('*' + SUFFIX)))


def manifest_path(script, root=ROOT, directory=None):
    name = Path(script).name[:-len(SUFFIX)]
    return (directory or Path(root) / config.get('gate-tests.covers_dir', ROOT)) / f'{name}.json'


def entry(raw, source):
    """Validate one {script, covers} object; returns the parsed entry."""
    if not isinstance(raw, dict):
        raise ScriptTestMapError(f'{source}: each test must be an object')
    script = raw.get('script')
    covers = raw.get('covers')
    if not isinstance(script, str) or not script.endswith(SUFFIX):
        raise ScriptTestMapError(f'{source}: test script must be a {SUFFIX} path')
    if not isinstance(covers, list) or not covers or not all(isinstance(item, str) and item for item in covers):
        raise ScriptTestMapError(f'{script}: covers must be a non-empty list of globs')
    return {'script': script, 'covers': tuple(covers)}


def load(root=ROOT):
    """The map; the registry is stat'ed once for the whole load (config.reading), not once per manifest path."""
    with config.reading():
        return _load(Path(root))


def _load(root):
    directory = root / config.get('gate-tests.covers_dir', ROOT)
    found = discover(root)
    parsed = []
    for script in found:
        target = manifest_path(script, root, directory)
        try:
            raw = json.loads(target.read_text())
        except OSError:
            raise ScriptTestMapError(f'{script}: no covers manifest {target.relative_to(root).as_posix()} (write one)') from None
        except json.JSONDecodeError as error:
            raise ScriptTestMapError(f'cannot read {target.relative_to(root).as_posix()}: {error}') from None
        item = entry(raw, target.name)
        if item['script'] != script:
            raise ScriptTestMapError(f'{target.relative_to(root).as_posix()} declares {item["script"]}, expected {script}')
        parsed.append(item)
    known = {manifest_path(script, root, directory).name for script in found}
    stray = sorted(path.name for path in directory.glob('*.json') if path.name not in known) if directory.is_dir() else []
    if stray:
        raise ScriptTestMapError(f'covers manifest without a script test: {", ".join(stray)}')
    traced = _traced(root)
    parsed = [{**item, 'traced': tuple(traced[item['script']])} if traced.get(item['script']) else item for item in parsed]
    fallback = config.get('gate-tests.fallback', ROOT)
    if not fallback:
        raise ScriptTestMapError('fallback must list the selector files')
    return {'fallback': tuple(fallback), 'tests': tuple(parsed), 'scripts': found}


def _traced(root):
    """{script: [code files]} of the traced map (gate-tests.traced_file, PADRAO-DEV F5b-2, D-317): what each test was
    measured to open that its covers did not select it for. Generated by scripts/padrao-metrics traced; none when absent."""
    target = root / config.get('gate-tests.traced_file', ROOT)
    try:
        raw = json.loads(target.read_text())
    except OSError:
        return {}
    except json.JSONDecodeError as error:
        raise ScriptTestMapError(f'cannot read {target.relative_to(root).as_posix()}: {error}') from None
    tests = raw.get('tests') if isinstance(raw, dict) else None
    if not isinstance(tests, dict) or not all(isinstance(files, list) and all(isinstance(path, str) for path in files)
                                              for files in tests.values()):
        raise ScriptTestMapError(f'{target.relative_to(root).as_posix()}: tests must map a script to a list of paths')
    return tests


def patterns(test):
    """What selects one test: its declared covers and its traced files."""
    return (*test['covers'], *test.get('traced', ()))


def _git_out(root, *args):
    done = subprocess.run(['git', '-C', str(root), *args], capture_output=True, text=True)
    return done.stdout if done.returncode == 0 else None


def traced_health(root=ROOT):
    """Freshness and integrity of the traced covers map (gate-tests.traced_file): base commit validity, merges behind
    HEAD, new script tests added since base that are not in the map, and any deleted script test or code path still
    listed. Returns None when no traced map exists under root."""
    root = Path(root)
    rel = config.get('gate-tests.traced_file', ROOT)
    target = root / rel
    if not target.is_file():
        return None
    raw = json.loads(target.read_text())
    tests = raw.get('tests') if isinstance(raw, dict) else None
    if not isinstance(tests, dict):
        raise ScriptTestMapError(f'{rel}: tests must map a script to a list of paths')
    base = str(raw.get('base') or '').strip()
    gone_tests = sorted(script for script in tests if not (root / script).is_file())
    gone_files = sorted({path for files in tests.values() for path in files if not (root / path).is_file()})
    base_valid, merges_behind, untraced_tests = None, None, []
    if base and _git_out(root, 'rev-parse', '--git-dir') is not None:
        base_valid = _git_out(root, 'rev-parse', '--verify', '-q', f'{base}^{{commit}}') is not None
        if base_valid:
            counted = _git_out(root, 'rev-list', '--count', '--first-parent', '--merges', f'{base}..HEAD')
            merges_behind = int(counted.strip()) if counted and counted.strip().isdigit() else 0
            added = _git_out(root, 'diff', '--name-only', '--diff-filter=A', f'{base}..HEAD', '--', 'scripts/tests/*.test.sh')
            untraced_tests = sorted(name for name in (added or '').splitlines()
                                    if name and name not in tests and (root / name).is_file())
    return {'file': rel, 'base': base, 'base_valid': base_valid, 'merges_behind': merges_behind,
            'gone_tests': gone_tests, 'gone_files': gone_files, 'untraced_tests': untraced_tests}


def traced_findings(root=ROOT):
    """(errors, warnings) of the traced covers map: deleted scripts/files or an unknown base commit are errors;
    a base behind HEAD or newly added untraced script tests are warnings."""
    try:
        health = traced_health(root)
    except (OSError, json.JSONDecodeError, ScriptTestMapError) as error:
        return [str(error)], []
    if health is None:
        return [], []
    rel = health['file']
    found_errors = [f'{rel}: lists script test {script}, which does not exist' for script in health['gone_tests']]
    found_errors += [f'{rel}: lists path {path}, which does not exist' for path in health['gone_files']]
    if health['base'] and health['base_valid'] is False:
        found_errors.append(f'{rel}: base commit {health["base"]} does not exist in git history')
    warnings = []
    if health['untraced_tests']:
        shown = ', '.join(health['untraced_tests'][:len('abc')])
        extra = len(health['untraced_tests']) - len('abc')
        tail = f' and {extra} more' if extra > 0 else ''
        behind = f'{health["merges_behind"]} merge(s) behind HEAD; ' if health['merges_behind'] else ''
        warnings.append(f'{rel}: base {health["base"]} is {behind}{len(health["untraced_tests"])} script test(s) '
                        f'added since were never traced ({shown}{tail})')
    elif health['merges_behind']:
        warnings.append(f'{rel}: base {health["base"]} is {health["merges_behind"]} merge(s) behind HEAD')
    return found_errors, warnings
