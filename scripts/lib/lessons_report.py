"""The pattern aggregator (LR1, D-069 items 4 and 9): which root-cause classes keep costing the queue.

Lessons are grouped by root-cause class. A lesson's `signals` count how often the class showed up in the event log and the
stage time it cost; classes are ranked by time lost, then occurrences, then lessons. The report is generated text with no
clock in it, so the same registry and log give the same digest and the lessons.reported event is published once.

  classes(records, events)   [class summary] ranked, the rows of the report
  render(records, events)    the Markdown report (docs/process/lessons.md)
  digest(text)               the hash of a report, the natural key of its event
  report_event(rows, text)   the lessons.reported payload fields
"""
import hashlib

import config
import lessons
import lessons_effect


def setting(name):
    return config.get(f'lessons.{name}')


def classes(records, events=()):
    """One row per class that has a lesson: lessons, units, statuses, occurrences, lost_ms, measurable."""
    rows = {}
    for record in records.values():
        row = rows.setdefault(record['class'], {'class': record['class'], 'lessons': [], 'signals': []})
        row['lessons'].append(record)
        row['signals'] += record['signals']
    ranked = []
    for row in rows.values():
        found = lessons_effect.occurrences(row['signals'], events)
        ranked.append({'class': row['class'], 'lessons': sorted(row['lessons'], key=lambda r: r['id']),
                       'units': sorted({r['source']['unit'] for r in row['lessons']}),
                       'occurrences': len(found), 'lost_ms': sum(cost for _, cost in found), 'measurable': bool(row['signals'])})
    return sorted(ranked, key=lambda r: (-r['lost_ms'], -r['occurrences'], -len(r['lessons']), r['class']))


def seconds(row):
    return f'{row["lost_ms"] / 1000:.1f} s' if row['measurable'] else setting('report_unknown_cost')


def status_count(row, status):
    return sum(1 for record in row['lessons'] if record['status'] == status)


def render(records, events=(), source='offline'):
    rows = classes(records, events)
    statuses = setting('statuses')
    head = ['class', 'lessons', 'units', *statuses, 'occurrences', 'time lost']
    lines = [f'# {setting("report_title")}', '',
             'Generated by `scripts/lessons report --write` from `docs/process/lessons/` (D-069 items 4 and 9). Do not edit by hand.',
             f'Event log: {source}. {len(records)} lesson(s) in {len(rows)} class(es), ranked by time lost, then occurrences, then lessons.', '',
             f'## Top {setting("report_top")} classes', '', '| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    for row in rows[:setting('report_top')]:
        cells = [row['class'], str(len(row['lessons'])), ', '.join(row['units']), *(str(status_count(row, s)) for s in statuses),
                 str(row['occurrences']) if row['measurable'] else setting('report_unknown_cost'), seconds(row)]
        lines.append('| ' + ' | '.join(cells) + ' |')
    for row in rows:
        lines += ['', f'## {row["class"]}', '']
        for record in row['lessons']:
            effect = record['effect']['verdict'] if record['effect'] else '-'
            lines.append(f'- `{record["id"]}` {record["status"]}, {record["kind"]}, {record["owner"]}, effect {effect}: {record["title"]}')
    return '\n'.join(lines) + '\n'


def digest(text):
    return hashlib.sha256(text.encode('utf-8')).hexdigest()[:setting('report_digest_chars')]


def report_event(records, events, text):
    rows = classes(records, events)
    return {'digest': digest(text), 'lessons': len(records), 'classes': len(rows),
            'top_class': rows[0]['class'] if rows else None, 'top_lost_ms': rows[0]['lost_ms'] if rows else 0}


def publish(port, records, events, text):
    """Emit lessons.reported once per distinct report (the natural key is the repository and the digest)."""
    if port is None:
        return None
    subject = lessons.forge_events.subject(config.get('forge-events.repo'), None, None, (), None)
    return port.emit('lessons.reported', dict(subject, **report_event(records, events, text)))
