"""The python-types target of scripts/generate (D-068 (5), D-069 items 1 and 2): Python types from the schemas.

Each source (contracts/**/*.json and config/registry/<owner>.json, as generate.targets lists them) becomes one module
of the target's output, named after its source path. A registry file gives `Name` (a Literal of its parameter names)
and `Values` (a TypedDict of their types); a contract gives one TypedDict per object in $defs and one for the root.
"""
import json
from pathlib import Path

import config
from generate import class_name, module_name, sources

SCALARS = {'integer': 'int', 'number': 'float', 'boolean': 'bool', 'string': 'str', 'null': 'None'}


def py_type(schema, root_class):
    if schema is True or not isinstance(schema, dict) or schema == {}:
        return 'Any'
    if '$ref' in schema:
        ref = schema['$ref']
        if not ref.startswith('#'):
            return 'Any'  # another file's definition: its own generated module types it
        return root_class if ref == '#' else class_name(ref.rsplit('/', 1)[-1])
    if 'const' in schema:
        return f'Literal[{schema["const"]!r}]'
    if 'enum' in schema and all(isinstance(item, (str, int, bool)) for item in schema['enum']):
        return 'Literal[' + ', '.join(repr(item) for item in schema['enum']) + ']'
    declared = schema.get('type')
    names = declared if isinstance(declared, list) else [declared] if declared else []
    if not names:
        return 'Any'
    parts = []
    for name in names:
        if name in SCALARS:
            parts.append(SCALARS[name])
        elif name == 'array':
            parts.append(f'list[{py_type(schema.get("items", True), root_class)}]')
        else:
            extra = schema.get('additionalProperties')
            value = py_type(extra, root_class) if isinstance(extra, dict) else 'Any'
            parts.append(f'dict[str, {value}]')
    return ' | '.join(parts)


def typed_dict(name, schema, root_class):
    required = set(schema.get('required', []))
    lines = [f'{name} = TypedDict({name!r}, {{']
    for key, child in schema.get('properties', {}).items():
        wrapper = 'Required' if key in required else 'NotRequired'
        lines.append(f'    {key!r}: {wrapper}[{py_type(child, root_class)}],')
    lines.append('}, total=False)')
    return lines


def render_module(source, document, registry):
    head = [f'"""Generated by scripts/generate python-types from {source} (D-068, D-069). Do not edit: the gate fails '
            'on drift."""',
            'from typing import Any, Literal, NotRequired, Required, TypedDict  # noqa: F401', '']
    if registry:
        names = list(document.get('properties', {}))
        body = ['Name = Literal['] + [f'    {name!r},' for name in names] + [']', '', "Values = TypedDict('Values', {"]
        body += [f'    {name!r}: {py_type(item, "Values")},' for name, item in document.get('properties', {}).items()]
        body += ['})']
    else:
        root_class = class_name(Path(source).with_suffix('').name)
        body = []
        for name, child in document.get('$defs', {}).items():
            if isinstance(child, dict) and child.get('type') == 'object':
                body += typed_dict(class_name(name), child, root_class) + ['', '']
            else:
                body += [f'{class_name(name)} = {py_type(child, root_class)}', '', '']
        if document.get('type') == 'object':
            body += typed_dict(root_class, document, root_class)
        else:
            body += [f'{root_class} = {py_type(document, root_class)}']
    return '\n'.join(head + body) + '\n'


def render(root, target):
    """{path: text} of every generated module and the package's __init__.py."""
    registry = config._registry_dir(root).relative_to(root).as_posix() + '/'
    out = {}
    for source in sources(root, target):
        document = json.loads((root / source).read_text(encoding='utf-8'))
        if not isinstance(document, dict):
            continue  # not a schema (contracts/events/schemas.lock.json lists the event schemas' hashes)
        out[f'{target["output"]}/{module_name(source)}.py'] = render_module(source, document,
                                                                            source.startswith(registry))
    out[f'{target["output"]}/__init__.py'] = ('"""Types generated by scripts/generate python-types (D-068, D-069). '
                                              'Do not edit."""\n')
    return out
