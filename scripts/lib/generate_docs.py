"""The docs target of scripts/generate (D-069 items 1 and 6): the registry and event catalog reference, on demand.

Rendered from the same sources as the types (config/registry/<owner>.json and the event schemas, as generate.targets
lists them) and never committed: `scripts/generate docs` prints it, `--out DIR` writes it. A committed copy would be
one more file to keep in step; the drift stage would then have to check it, so it stays on demand until a reader
needs a file.
"""
import json
from pathlib import Path

import config
from generate import sources
from json_schema import EVENT_PAYLOAD_FILE as PAYLOAD_FILE


def cell(value):
    return str(value).replace('|', '\\|').replace('\n', ' ')


def code(value):
    return f'`{cell(json.dumps(value, ensure_ascii=False))}`'


def summary(schema):
    """A short type of one property: its $ref, const, enum or type names."""
    if not isinstance(schema, dict) or not schema:
        return 'any'
    if '$ref' in schema:
        return schema['$ref']
    if 'const' in schema:
        return code(schema['const'])
    if 'enum' in schema:
        return ' \\| '.join(code(item) for item in schema['enum'])
    declared = schema.get('type')
    names = declared if isinstance(declared, list) else [declared] if declared else ['any']
    if 'array' in names:
        names = [f'array of {summary(schema.get("items"))}' if name == 'array' else name for name in names]
    return ', '.join(names)


def registry_page(root, paths):
    lines = ['# Configuration registry reference', '',
             'Generated by `scripts/generate docs` from `config/registry/<owner>.json` (D-068). Read a value with',
             '`scripts/config get <name>`; change it with `scripts/config set`.', '']
    for path in paths:
        document = json.loads((root / path).read_text(encoding='utf-8'))
        lines += [f'## {document.get("x-owner", Path(path).stem)}', '', f'Source: `{path}`.', '']
        if document.get('description'):
            lines += [document['description'], '']
        lines += ['| Parameter | Type | Default | Unit | Description | Readers |', '|---|---|---|---|---|---|']
        for name, item in (document.get('properties') or {}).items():
            readers = ', '.join(f'`{reader}`' for reader in item.get('x-readers') or [])
            kind = item.get('type', 'any') + (' (flag)' if item.get('x-flag') else '')
            if item.get('deprecated'):
                kind += ' (deprecated)'
            lines.append(f'| `{name}` | {kind} | {code(item.get("default"))} | {cell(item.get("x-unit", ""))} | '
                         f'{cell(item.get("description", ""))} | {readers} |')
        lines.append('')
    return '\n'.join(lines)


def event_page(root, paths):
    lines = ['# Event catalog reference', '',
             'Generated by `scripts/generate docs` from the event schemas (D-065, D-069 item 4). Every event is the',
             'envelope of `envelope.v1.json` around one of these payloads.', '']
    events = []
    for path in paths:
        match = PAYLOAD_FILE.match(Path(path).name)
        if match:
            events.append((match['type'], int(match['version']), path))
    for kind, version, path in sorted(events):
        document = json.loads((root / path).read_text(encoding='utf-8'))
        required = set(document.get('required', []))
        lines += [f'## {kind} v{version}', '', f'Source: `{path}`.', '']
        if document.get('description'):
            lines += [document['description'], '']
        if document.get('x-natural-key'):
            lines += ['Natural key: ' + ', '.join(f'`{pointer}`' for pointer in document['x-natural-key']) + '.', '']
        lines += ['| Field | Type | Required | Description |', '|---|---|---|---|']
        for name, child in (document.get('properties') or {}).items():
            text = child.get('description', '') if isinstance(child, dict) else ''
            lines.append(f'| `{name}` | {summary(child)} | {"yes" if name in required else "no"} | {cell(text)} |')
        lines.append('')
    return '\n'.join(lines)


def render(root, target):
    """{path: text}: the registry reference and the event catalog under the target's output."""
    registry = config._registry_dir(root).relative_to(root).as_posix() + '/'
    found = sources(root, target)
    return {
        f'{target["output"]}/config-registry.md': registry_page(root, [p for p in found if p.startswith(registry)]),
        f'{target["output"]}/event-catalog.md': event_page(root, [p for p in found if not p.startswith(registry)]),
    }
