"""The DNS of openuniversity.si on Route 53 (D-323 step 3): from Cloudflare's BIND export to a checked-in record list and
from that list to the CloudFormation stack infra/aws/stacks/70-dns.json. Offline: it reads files and writes files, never
the network.

  build <bind-file> [--targets F]   parse the export, write the record list (infra/aws/dns/<zone>.json) and the stack
  template [--check]                write the stack from the record list (--check: exit 1 when the committed one differs)
  compare <bind-file> [--targets F] the export against the record list: every record, its values and its TTL; exit 1 on a
                                    difference
  dig-plan [--ns a,b,c,d]           one `dig` per record against a Route 53 name server, with the answer it must give

A record Cloudflare proxies is refused: the export holds Cloudflare's anycast address (or, for a proxied CNAME, a target
Cloudflare fronts), never the origin behind it, so translating it would point the name at Cloudflare or bypass what it
did. It is listed under needs_target; the real target goes into the targets file (infra/aws/dns/<zone>.targets.json) and
the next build takes it from there. The proxy ranges are read from infra/aws/dns/cloudflare-ips.json, never from code.
The apex's NS and SOA are dropped (Route 53 writes its own). A CNAME at the apex (Cloudflare flattens it) to a CloudFront
domain becomes an alias A and AAAA to the distribution named by the stack's SiteDistribution parameter.

A target is either a record ({"type": ..., "values": [...], "ttl": ...}) or a CloudFormation export of another stack that
holds a CloudFront domain ({"alias_import": "<export name>"}): the record becomes an alias A and AAAA whose DNSName is
Fn::ImportValue of that export (hosted zone Z2FDTNDATAQYW2, CloudFront's), so the session never copies a domain it cannot
read. The stack that exports it must come first in infra/aws/order.json (StackOrderTests derives the edge from the
import), and while the dns stack imports it CloudFormation refuses to change or remove that export in the other stack.
Stdlib only, deterministic (sorted output, no clock).
"""
import argparse
import hashlib
import ipaddress
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
ZONE = 'openuniversity.si.'
DNS = ROOT / 'infra/aws/dns'
STACK = ROOT / 'infra/aws/stacks/70-dns.json'
PROXY_IPS = DNS / 'cloudflare-ips.json'
CLOUDFRONT_ZONE_ID = 'Z2FDTNDATAQYW2'  # the hosted zone id every CloudFront alias target carries (AWS's, fixed)
AUTO_TTL = 300  # Cloudflare's "auto" TTL, exported as 1, is 300 s
EXPORT_NAME = re.compile(r'^[A-Za-z0-9:-]{1,255}$')  # what CloudFormation takes as an export name
MAX_BODY = 51200  # what `aws cloudformation deploy` sends without an S3 bucket
TYPES = {'A', 'AAAA', 'CAA', 'CNAME', 'DS', 'HTTPS', 'MX', 'NAPTR', 'NS', 'PTR', 'SOA', 'SPF', 'SRV', 'SSHFP', 'SVCB',
         'TLSA', 'TXT'}  # what Route 53 serves
CLASSES = {'IN', 'CH', 'HS'}
TTL = re.compile(r'^(\d+[smhdwSMHDW]?)+$')
UNITS = {'': 1, 's': 1, 'm': 60, 'h': 60 * 60, 'd': 24 * 60 * 60, 'w': 7 * 24 * 60 * 60}
DESCRIPTION = (
    'The DNS of openuniversity.si on Route 53 (D-323 step 3), generated by scripts/dns-zone from the record list '
    'infra/aws/dns/openuniversity.si.json (never edited by hand). Zone off (the first deploy, before the Torre re-applies '
    'the bootstrap with route53 in the boundary) is a wait-condition handle alone; Zone on is the hosted zone, retained, '
    'its four name servers an output, and one record set per name and type of the list; an apex CNAME to CloudFront is an '
    'alias A and AAAA to SiteDistribution, absent while it is empty; a target named by an export is an alias A and AAAA '
    'to its Fn::ImportValue (the exporting stack comes first in order.json). Cost: US$ 0.50 a month for the zone plus US$ 0.40 '
    'per million queries (alias queries to CloudFront are free); the query volume is not known, so the bound is '
    '10 million queries a month: at most US$ 4.50 a month.')


class ZoneError(Exception):
    pass


# --- the BIND file -------------------------------------------------------------------------------------------------------

def _lines(text):
    """Logical lines: (lineno, starts_blank, tokens, comment). A token is a str (bare) or ('q', text) (quoted, decoded);
    parentheses join physical lines; `;` outside quotes starts a comment."""
    out, tokens, comment, depth, start, blank = [], [], '', 0, 1, False
    i, n, lineno, at_line_start = 0, len(text), 1, True
    while i < n:
        ch = text[i]
        if at_line_start and depth == 0:
            start, blank, tokens, comment = lineno, ch in ' \t', [], ''
            at_line_start = False
        if ch == '\n':
            lineno += 1
            i += 1
            if depth == 0:
                if tokens:
                    out.append((start, blank, tokens, comment))
                at_line_start = True
            continue
        if ch in ' \t\r':
            i += 1
            continue
        if ch == ';':
            j = text.find('\n', i)
            j = n if j < 0 else j
            comment += text[i + 1:j]
            i = j
            continue
        if ch == '(':
            depth += 1
            i += 1
            continue
        if ch == ')':
            if not depth:
                raise ZoneError(f'line {lineno}: ")" with no "("')
            depth -= 1
            i += 1
            continue
        if ch == '"':
            j, buf = i + 1, []
            while True:
                if j >= n:
                    raise ZoneError(f'line {lineno}: a quoted string is not closed')
                c = text[j]
                if c == '"':
                    break
                if c == '\\' and j + 1 < n:
                    if text[j + 1:j + 4].isdigit() and len(text[j + 1:j + 4]) == 3:
                        buf.append(chr(int(text[j + 1:j + 4])))
                        j += 4
                        continue
                    buf.append(text[j + 1])
                    j += 2
                    continue
                if c == '\n':
                    lineno += 1
                buf.append(c)
                j += 1
            tokens.append(('q', ''.join(buf)))
            i = j + 1
            continue
        j = i
        while j < n and text[j] not in ' \t\r\n;()"':
            j += 1
        tokens.append(text[i:j])
        i = j
    if depth:
        raise ZoneError('a "(" is not closed at the end of the file')
    if tokens and not at_line_start:
        out.append((start, blank, tokens, comment))
    return out


def _seconds(token):
    total = 0
    for number, unit in re.findall(r'(\d+)([smhdwSMHDW]?)', token):
        total += int(number) * UNITS[unit.lower()]
    return total


def _fqdn(name, origin):
    name = name.lower()
    if name == '@':
        return origin
    if name.endswith('.'):
        return name
    if origin != '.' and (name + '.' == origin or (name + '.').endswith('.' + origin)):
        return name + '.'  # Cloudflare writes some owners (the SOA's) whole but with no final dot
    return f'{name}.{origin}' if origin != '.' else name + '.'


def _bare(token, line):
    if isinstance(token, tuple):
        raise ZoneError(f'line {line}: a quoted string where a name or number goes')
    return token


def _quote(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def _rdata(rtype, tokens, origin, line):
    """The record's value in one normal form (the form Route 53 takes, except TXT, kept as its joined text)."""
    def need(count):
        if len(tokens) != count:
            raise ZoneError(f'line {line}: {rtype} takes {count} fields, not {len(tokens)}')
    try:
        if rtype == 'A':
            need(1)
            return str(ipaddress.IPv4Address(_bare(tokens[0], line)))
        if rtype == 'AAAA':
            need(1)
            return ipaddress.IPv6Address(_bare(tokens[0], line)).compressed
        if rtype in ('CNAME', 'NS', 'PTR'):
            need(1)
            return _fqdn(_bare(tokens[0], line), origin)
        if rtype == 'MX':
            need(2)
            return f'{int(_bare(tokens[0], line))} {_fqdn(_bare(tokens[1], line), origin)}'
        if rtype == 'SRV':
            need(4)
            numbers = [int(_bare(token, line)) for token in tokens[:3]]
            target = _bare(tokens[3], line)
            return ' '.join(map(str, numbers)) + ' ' + ('.' if target == '.' else _fqdn(target, origin))
        if rtype == 'CAA':
            need(3)
            value = tokens[2][1] if isinstance(tokens[2], tuple) else tokens[2]
            return f'{int(_bare(tokens[0], line))} {_bare(tokens[1], line).lower()} {_quote(value)}'
        if rtype in ('TXT', 'SPF'):
            if not tokens:
                raise ZoneError(f'line {line}: {rtype} with no string')
            return ''.join(token[1] if isinstance(token, tuple) else token for token in tokens)
    except ValueError as error:
        raise ZoneError(f'line {line}: {rtype} {error}') from None
    return ' '.join(_quote(token[1]) if isinstance(token, tuple) else token for token in tokens)


def parse(text, zone=ZONE):
    """Every resource record of a BIND zone file: [{name, type, ttl, value, line, proxied_tag}] (names absolute, lower)."""
    origin, default_ttl, owner, records = zone, None, None, []
    for line, blank, tokens, comment in _lines(text):
        head = tokens[0] if isinstance(tokens[0], str) else ''
        if head.upper() == '$ORIGIN':
            origin = _fqdn(_bare(tokens[1], line), origin)
            continue
        if head.upper() == '$TTL':
            default_ttl = _seconds(_bare(tokens[1], line))
            continue
        if head.startswith('$'):
            raise ZoneError(f'line {line}: {head} is not read here (only $ORIGIN and $TTL)')
        rest = tokens
        if not blank:
            owner, rest = _fqdn(_bare(tokens[0], line), origin), tokens[1:]
        if owner is None:
            raise ZoneError(f'line {line}: a record with no owner name')
        ttl, rtype = None, None
        while rest:
            token = _bare(rest[0], line)
            if ttl is None and TTL.match(token):
                ttl = _seconds(token)
            elif token.upper() in CLASSES:
                if token.upper() != 'IN':
                    raise ZoneError(f'line {line}: class {token} (only IN)')
            else:
                rtype = token.upper()
                rest = rest[1:]
                break
            rest = rest[1:]
        if rtype is None:
            raise ZoneError(f'line {line}: no record type')
        if rtype not in TYPES:
            raise ZoneError(f'line {line}: type {rtype} is not one Route 53 serves')
        if ttl is None:
            ttl = default_ttl
        if ttl is None:
            raise ZoneError(f'line {line}: no TTL and no $TTL before it')
        records.append({'name': owner, 'type': rtype, 'ttl': ttl, 'value': _rdata(rtype, rest, origin, line),
                        'line': line, 'proxied_tag': 'cf-proxied:true' in comment.replace(' ', '').lower()})
    return records


# --- the record list -----------------------------------------------------------------------------------------------------

def proxy_networks(path=PROXY_IPS):
    data = json.loads(Path(path).read_text(encoding='utf-8'))
    return [ipaddress.ip_network(cidr) for cidr in data['ipv4'] + data['ipv6']]


def _proxied_value(record, networks):
    if record['type'] in ('A', 'AAAA'):
        address = ipaddress.ip_address(record['value'])
        return any(address.version == net.version and address in net for net in networks)
    return False


def _key(record):
    return f"{record['name']} {record['type']}"


def normalize(records, zone=ZONE, networks=(), targets=None):
    """(kept, needs_target, dropped): the record sets Route 53 gets, the ones refused, the apex NS/SOA dropped."""
    targets = targets or {}
    sets, order = {}, []
    for record in records:
        key = (record['name'], record['type'])
        if key not in sets:
            sets[key] = []
            order.append(key)
        sets[key].append(record)
    kept, refused, dropped = [], [], []
    for name, rtype in sorted(order):
        group = sets[(name, rtype)]
        if name == zone and rtype in ('NS', 'SOA'):
            dropped.append(f'{name} {rtype}')
            continue
        ttls = {AUTO_TTL if record['ttl'] == 1 else record['ttl'] for record in group}
        if len(ttls) > 1:
            raise ZoneError(f'{name} {rtype}: one record set with TTLs {sorted(ttls)} (Route 53 takes one TTL per set)')
        ttl = ttls.pop()
        values = sorted({record['value'] for record in group})
        item = {'name': name, 'type': rtype, 'ttl': ttl, 'values': values}
        reason = None
        if any(_proxied_value(record, networks) for record in group):
            reason = 'a Cloudflare proxy address (proxied): the real origin is not in the export'
        elif any(record['proxied_tag'] for record in group):
            reason = 'proxied by Cloudflare (cf-proxied:true): what it fronts is not a target to copy'
        elif rtype == 'CNAME' and name == zone and not (len(values) == 1 and values[0].endswith('.cloudfront.net.')):
            reason = 'a CNAME at the apex: Route 53 takes it only as an alias to an AWS target'
        if reason:
            target = targets.get(_key(item))
            if target is None:
                refused.append({**item, 'reason': reason})
                continue
            item = _replacement(item, target, reason)
        if rtype == 'CNAME' and name == zone and 'replaces' not in item:
            item['route53'] = 'alias A and AAAA to the CloudFront distribution SiteDistribution'
        kept.append(item)
    names = {}
    for item in kept:
        names.setdefault(item['name'], set()).add(item['type'])
    for name, types in sorted(names.items()):
        if 'ALIAS' in types and types & {'A', 'AAAA'}:
            raise ZoneError(f'{name}: the alias to an export is an A and AAAA, and the list has A or AAAA there too')
    for name, types in sorted(names.items()):
        if 'CNAME' in types and len(types) > 1 and name != zone:
            raise ZoneError(f'{name}: a CNAME beside {sorted(types - {"CNAME"})} (a CNAME stands alone)')
        if name == zone and 'CNAME' in types and types & {'A', 'AAAA'}:
            raise ZoneError(f'{name}: the apex CNAME becomes an alias A and AAAA, and the export has A or AAAA there too')
    return kept, refused, dropped


def _replacement(item, target, reason):
    """The record Route 53 gets in place of a refused one: the target's record, or an alias to an export's domain."""
    replaces = f'{_key(item)} ({reason})'
    if 'alias_import' in target:
        export = target['alias_import']
        if not isinstance(export, str) or not EXPORT_NAME.match(export) or set(target) - {'alias_import'}:
            raise ZoneError(f'{_key(item)}: a target {{"alias_import": "<export name>"}} names one CloudFormation export '
                            f'(letters, digits, ":" and "-") and nothing else, not {json.dumps(target, sort_keys=True)}')
        return {'name': item['name'], 'type': 'ALIAS', 'ttl': item['ttl'], 'values': [], 'alias_import': export,
                'route53': f'alias A and AAAA to the CloudFront domain the export {export} holds (Fn::ImportValue)',
                'replaces': replaces}
    return {'name': item['name'], 'type': target['type'], 'ttl': int(target.get('ttl', item['ttl'])),
            'values': sorted(target['values']), 'replaces': replaces}


def site_alias(item):
    """The apex alias to SiteDistribution (an export's alias names its own target)."""
    return item.get('route53', '').startswith('alias') and not item.get('alias_import')


def record_list(text, source_name, zone=ZONE, networks=(), targets=None):
    kept, refused, dropped = normalize(parse(text, zone), zone, networks, targets)
    return {
        'zone': zone,
        'generated_by': 'scripts/dns-zone build (do not edit by hand: rebuild from the export)',
        'export': {'file': source_name, 'sha256': hashlib.sha256(text.encode('utf-8')).hexdigest()},
        'ttl_note': f"Cloudflare exports its automatic TTL as 1; it is {AUTO_TTL} s here",
        'records': kept,
        'needs_target': refused,
        'dropped': dropped,
    }


def load_targets(path):
    path = Path(path)
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding='utf-8')).get('targets', {})


# --- the stack -----------------------------------------------------------------------------------------------------------

def txt_value(text):
    """A TXT value as Route 53 takes it: quoted strings of at most 255 octets, `"` and `\\` escaped, other bytes \\DDD."""
    data = text.encode('utf-8')
    chunks = [data[i:i + 255] for i in range(0, len(data), 255)] or [b'']
    def escape(chunk):
        out = []
        for byte in chunk:
            char = chr(byte)
            if char in '"\\':
                out.append('\\' + char)
            elif 0x20 <= byte < 0x7f:
                out.append(char)
            else:
                out.append(f'\\{byte:03d}')
        return '"' + ''.join(out) + '"'
    return ' '.join(escape(chunk) for chunk in chunks)


def route53_values(item):
    if item['type'] in ('TXT', 'SPF'):
        return [txt_value(value) for value in item['values']]
    return list(item['values'])


def logical_id(item, zone, taken):
    relative = item['name'][:-len(zone)].rstrip('.') if item['name'].endswith(zone) else item['name']
    words = re.split(r'[^A-Za-z0-9*]+', relative)
    base = ''.join('Wildcard' if word == '*' else word[:1].upper() + word[1:] for word in words if word) or 'Apex'
    candidate = 'Record' + base.replace('*', 'Wildcard') + item['type'].title()
    if candidate in taken:
        candidate += hashlib.sha256(f"{item['name']} {item['type']}".encode()).hexdigest()[:8]
    taken.add(candidate)
    return candidate


def template(data):
    zone = data['zone']
    resources = {
        'Pending': {'Type': 'AWS::CloudFormation::WaitConditionHandle', 'Condition': 'ZoneOff', 'Properties': {}},
        'HostedZone': {
            'Type': 'AWS::Route53::HostedZone', 'Condition': 'ZoneOn',
            'DeletionPolicy': 'Retain', 'UpdateReplacePolicy': 'Retain',
            'Properties': {'Name': zone, 'HostedZoneConfig': {
                'Comment': 'openuniversity.si (D-323 step 3), from infra/aws/dns by scripts/dns-zone'}},
        },
    }
    taken = set(resources)
    for item in data['records']:
        if item.get('alias_import'):
            for rtype in ('A', 'AAAA'):
                resources[logical_id({**item, 'type': rtype}, zone, taken)] = {
                    'Type': 'AWS::Route53::RecordSet', 'Condition': 'ZoneOn',
                    'Properties': {'HostedZoneId': {'Ref': 'HostedZone'}, 'Name': item['name'], 'Type': rtype,
                                   'AliasTarget': {'DNSName': {'Fn::ImportValue': item['alias_import']},
                                                   'HostedZoneId': CLOUDFRONT_ZONE_ID, 'EvaluateTargetHealth': False}}}
            continue
        if site_alias(item):
            for rtype in ('A', 'AAAA'):
                resources[logical_id({**item, 'type': rtype}, zone, taken)] = {
                    'Type': 'AWS::Route53::RecordSet', 'Condition': 'SiteKnown',
                    'Properties': {'HostedZoneId': {'Ref': 'HostedZone'}, 'Name': item['name'], 'Type': rtype,
                                   'AliasTarget': {'DNSName': {'Ref': 'SiteDistribution'},
                                                   'HostedZoneId': CLOUDFRONT_ZONE_ID, 'EvaluateTargetHealth': False}}}
            continue
        resources[logical_id(item, zone, taken)] = {
            'Type': 'AWS::Route53::RecordSet', 'Condition': 'ZoneOn',
            'Properties': {'HostedZoneId': {'Ref': 'HostedZone'}, 'Name': item['name'], 'Type': item['type'],
                           'TTL': str(item['ttl']), 'ResourceRecords': route53_values(item)}}
    off = {'Fn::Equals': [{'Ref': 'Zone'}, 'off']}
    return {
        'AWSTemplateFormatVersion': '2010-09-09',
        'Description': DESCRIPTION,
        'Parameters': {
            'Zone': {'Type': 'String', 'Default': 'off', 'AllowedValues': ['off', 'on'],
                     'Description': 'on creates the hosted zone and its records; off (until the boundary allows route53) '
                                    'creates nothing that bills'},
            'SiteDistribution': {
                'Type': 'String', 'Default': '', 'AllowedPattern': r'^$|^[a-z0-9]+\.cloudfront\.net$',
                'Description': "the site's CloudFront domain the apex aliases (A and AAAA); empty: no apex record yet"},
        },
        'Conditions': {
            'ZoneOff': off,
            'ZoneOn': {'Fn::Not': [off]},
            'SiteKnown': {'Fn::And': [{'Condition': 'ZoneOn'},
                                      {'Fn::Not': [{'Fn::Equals': [{'Ref': 'SiteDistribution'}, '']}]}]},
        },
        'Resources': resources,
        'Outputs': {
            'ZoneId': {'Condition': 'ZoneOn', 'Value': {'Ref': 'HostedZone'}},
            'NameServers': {'Condition': 'ZoneOn', 'Description': 'the four name servers the registrar gets',
                            'Value': {'Fn::Join': [',', {'Fn::GetAtt': ['HostedZone', 'NameServers']}]}},
        },
    }


def render(data):
    body = json.dumps(template(data), indent=2, ensure_ascii=False) + '\n'
    if len(body.encode('utf-8')) > MAX_BODY:
        raise ZoneError(f'the stack is {len(body.encode())} bytes, over the {MAX_BODY} `aws cloudformation deploy` '
                        'sends without an S3 bucket')
    if len(template(data)['Resources']) > 500:
        raise ZoneError('over 500 resources in one stack')
    return body


def dump(data):
    return json.dumps(data, indent=2, ensure_ascii=False) + '\n'


# --- compare and dig ------------------------------------------------------------------------------------------------------

def compare(text, data, networks=(), targets=None):
    """The differences between an export and the record list, and the records that need their real target."""
    zone = data['zone']
    kept, refused, _ = normalize(parse(text, zone), zone, networks, targets)
    want = {_key(item): item for item in kept}
    have = {_key(item): item for item in data['records']}
    problems = []
    for key, item in sorted(want.items()):
        got = have.get(key)
        if got is None:
            problems.append(f'missing from the record list: {key} {item["values"]}')
        elif (got['ttl'], got['values'], got.get('alias_import')) != (item['ttl'], item['values'], item.get('alias_import')):
            problems.append(f'differs: {key} export ttl {item["ttl"]} {item["values"] or item.get("alias_import")}, '
                            f'list ttl {got["ttl"]} {got["values"] or got.get("alias_import")}')
    for key in sorted(set(have) - set(want)):
        problems.append(f'in the record list, not in the export: {key}')
    listed = {_key(item) for item in data.get('needs_target', [])}
    for key in sorted({_key(item) for item in refused} ^ listed):
        problems.append(f'needs its real target in one and not the other: {key}')
    return problems, refused


def dig_plan(data, name_servers, site=''):
    ns = name_servers[0] if name_servers else '<route53-ns>'
    lines = [f'# against {ns} (Route 53 answers for the zone before the registrar points at it)']
    for server in name_servers or ['<route53-ns>']:
        lines.append(f'dig +norecurse @{server} {data["zone"]} SOA +short  # the zone answers on {server}')
    for item in data['records']:
        if item.get('alias_import'):
            for rtype in ('A', 'AAAA'):
                lines.append(f'dig +norecurse @{ns} {item["name"]} {rtype} +short  # expect the addresses of the '
                             f'CloudFront domain the export {item["alias_import"]} holds (alias)')
            continue
        if site_alias(item):
            for rtype in ('A', 'AAAA'):
                lines.append(f'dig +norecurse @{ns} {item["name"]} {rtype} +short  # expect the addresses of '
                             f'{site or "<SiteDistribution>"} (alias)')
            continue
        expect = ' | '.join(route53_values(item))
        lines.append(f'dig +norecurse @{ns} {item["name"]} {item["type"]} +short  # expect ttl {item["ttl"]}: {expect}')
    for item in data.get('needs_target', []):
        lines.append(f'# not in Route 53 until its real target is known: {_key(item)} ({item["reason"]})')
    return '\n'.join(lines) + '\n'


# --- the command ----------------------------------------------------------------------------------------------------------

def default_list(zone=ZONE):
    return DNS / f'{zone.rstrip(".")}.json'


def default_targets(zone=ZONE):
    return DNS / f'{zone.rstrip(".")}.targets.json'


def main(argv=None):
    parser = argparse.ArgumentParser(prog='scripts/dns-zone', description=__doc__.split('\n')[0])
    sub = parser.add_subparsers(dest='command', required=True)
    for name in ('build', 'compare'):
        cmd = sub.add_parser(name)
        cmd.add_argument('bind_file')
        cmd.add_argument('--targets', default=str(default_targets()))
    template_cmd = sub.add_parser('template')
    template_cmd.add_argument('--check', action='store_true')
    dig = sub.add_parser('dig-plan')
    dig.add_argument('--ns', default='', help='the zone\'s name servers, comma-separated (the stack output NameServers)')
    dig.add_argument('--site', default='', help='the SiteDistribution the apex aliases')
    for cmd in (sub.choices['build'], sub.choices['compare'], template_cmd, dig):
        cmd.add_argument('--list', default=str(default_list()))
        cmd.add_argument('--stack', default=str(STACK))
        cmd.add_argument('--proxy-ips', default=str(PROXY_IPS))
    args = parser.parse_args(argv)
    try:
        if args.command == 'build':
            text = Path(args.bind_file).read_text(encoding='utf-8')
            data = record_list(text, Path(args.bind_file).name, ZONE, proxy_networks(args.proxy_ips),
                               load_targets(args.targets))
            body = render(data)
            Path(args.list).write_text(dump(data), encoding='utf-8')
            Path(args.stack).write_text(body, encoding='utf-8')
            print(f'{len(data["records"])} record sets -> {args.list} and {args.stack}; dropped: '
                  f'{", ".join(data["dropped"]) or "none"}')
            for item in data['records']:
                if item.get('alias_import'):
                    print(f'{item["name"]} alias: A and AAAA to the export {item["alias_import"]}; the stack that exports '
                          'it comes first in infra/aws/order.json')
                elif site_alias(item):
                    print(f'apex alias: set infra/aws/parameters.json dns.SiteDistribution to '
                          f'{item["values"][0].rstrip(".")}')
            for item in data['needs_target']:
                print(f'needs its real target: {_key(item)} {item["values"]} ({item["reason"]}); '
                      f'put it in {args.targets}')
            return 0
        if args.command == 'template':
            data = json.loads(Path(args.list).read_text(encoding='utf-8'))
            body = render(data)
            if args.check:
                current = Path(args.stack).read_text(encoding='utf-8') if Path(args.stack).exists() else ''
                if current != body:
                    print(f'{args.stack} is not the stack of {args.list}: run scripts/dns-zone template', file=sys.stderr)
                    return 1
                print(f'{args.stack} is the stack of {args.list}')
                return 0
            Path(args.stack).write_text(body, encoding='utf-8')
            print(f'wrote {args.stack}')
            return 0
        if args.command == 'compare':
            data = json.loads(Path(args.list).read_text(encoding='utf-8'))
            text = Path(args.bind_file).read_text(encoding='utf-8')
            problems, refused = compare(text, data, proxy_networks(args.proxy_ips), load_targets(args.targets))
            for item in refused:
                print(f'needs its real target: {_key(item)} {item["values"]} ({item["reason"]})')
            for problem in problems:
                print(problem)
            if problems:
                print(f'{len(problems)} difference(s) between {args.bind_file} and {args.list}', file=sys.stderr)
                return 1
            print(f'the record list matches the export: {len(data["records"])} record sets, '
                  f'{len(refused)} needing their real target')
            return 0
        data = json.loads(Path(args.list).read_text(encoding='utf-8'))
        servers = [server.strip() for server in args.ns.split(',') if server.strip()]
        sys.stdout.write(dig_plan(data, servers, args.site))
        return 0
    except (ZoneError, OSError, KeyError, json.JSONDecodeError) as error:
        print(f'dns-zone: {error}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    sys.exit(main())
