class Driver(Fixture):
    def override(self, **targets):
        document = json.loads((self.root / 'config/registry/generate.json').read_text())
        document['properties']['generate.targets']['default'] = [{**target, 'name': name}
                                                                 for name, target in targets.items()]
        self.write('config/registry/generate.json', document)

    def test_a_disabled_target_is_skipped_and_listed(self):
        self.override(**{'python-types': {**self.target('python-types'), 'enabled': False,
                                          'requires': 'units/*/unit.json', 'slot': 'G1b'}})
        code, out = self.generate('--check')
        self.assertEqual(code, 0)
        self.assertIn('skip python-types: disabled until units/*/unit.json exists (G1b)', out)
        self.assertEqual(self.generate('python-types')[0], 0)
        self.assertFalse((self.root / 'scripts/lib/generated').exists())

    def test_an_enabled_target_waits_for_its_requirement(self):
        self.override(**{'python-types': {**self.target('python-types'), 'requires': 'units/*/unit.json'}})
        self.assertIn('nothing matches units/*/unit.json', self.generate('--list')[1])
        self.write('units/web/unit.json', {})
        self.assertIn('\tenabled\t', self.generate('--list')[1])

    def test_an_unknown_target_a_missing_renderer_or_a_twice_declared_name_is_an_error(self):
        types = self.target('python-types')
        with self.assertRaises(SystemExit), contextlib.redirect_stderr(io.StringIO()):
            self.generate('nope')
        self.override(**{'no-such': types})
        with self.assertRaisesRegex(generate.GenerateError, 'no renderer scripts/lib/generate_no_such.py'):
            self.generate('no-such')
        self.override(**{'python-types': types})
        document = json.loads((self.root / 'config/registry/generate.json').read_text())
        document['properties']['generate.targets']['default'] *= 2
        document['properties']['generate.targets']['uniqueItems'] = False
        self.write('config/registry/generate.json', document)
        with self.assertRaisesRegex(generate.GenerateError, 'declares python-types twice'):
            generate.targets(self.root)

    def test_out_writes_elsewhere_and_leaves_the_tree(self):
        with tempfile.TemporaryDirectory() as out:
            self.generate('python-types', '--out', out)
            self.assertTrue((Path(out) / 'scripts/lib/generated/config_registry_train.py').is_file())
        self.assertFalse((self.root / 'scripts/lib/generated').exists())


class DriftStage(unittest.TestCase):
    STAGE = 'generated drift'

    def test_the_stage_runs_on_every_plan_without_an_install(self):
        self.assertIn(self.STAGE, gate_policy.PREREQUISITES)
        areas = gate_areas.load()
        self.assertIn(self.STAGE, areas.order)
        for plan in (gate_areas.plan_for(['docs/x.md']), gate_areas.plan_for(['products/demo/src/ui/x.tsx'])):
            self.assertIn(self.STAGE, plan['stages'])
        self.assertIn(f'launch step_cached_by_inputs "{self.STAGE}" "$root" "" "$tool_root/scripts/generate" --check',
                      (ROOT / 'scripts/gate-local').read_text())


