import { z } from "zod";
import { metaDot } from "../../../site/domain/reader-copy.ts";
import { courseBundleDocSchema } from "./bundle.ts";
import { DEFAULTS, EDITION_YEARS, LIMITS } from "./fields.ts";

// docs/catalog/schema.md is rendered from the zod schema, never written by hand (INV-R1). `pnpm schema:check` compares.

export const SCHEMA_DOC_PATH = "docs/catalog/schema.md";

interface JsonNode {
  readonly type?: string | readonly string[];
  readonly const?: unknown;
  readonly enum?: readonly unknown[];
  readonly default?: unknown;
  readonly pattern?: string;
  readonly minLength?: number;
  readonly maxLength?: number;
  readonly minimum?: number;
  readonly maximum?: number;
  readonly exclusiveMinimum?: number;
  readonly anyOf?: readonly JsonNode[];
  readonly items?: JsonNode;
  readonly properties?: Readonly<Record<string, JsonNode>>;
  readonly required?: readonly string[];
}

const nonNull = (node: JsonNode): JsonNode => node.anyOf?.find((option) => option.type !== "null") ?? node;
const nullable = (node: JsonNode): boolean => node.anyOf?.some((option) => option.type === "null") === true || (Array.isArray(node.type) && node.type.includes("null"));
const show = (value: unknown): string => `\`${JSON.stringify(value)}\``;

function typeOf(node: JsonNode): string {
  const inner = nonNull(node);
  const base = inner.const !== undefined ? show(inner.const)
    : inner.enum ? inner.enum.map(show).join(metaDot)
    : inner.type === "array" ? `list of ${inner.items?.properties ? "objects" : typeOf(inner.items ?? {})}`
    : inner.properties ? "object"
    : (Array.isArray(inner.type) ? inner.type.filter((type) => type !== "null") : [inner.type ?? "any"]).join(metaDot);
  return nullable(node) ? `${base} or null` : base;
}

function ruleOf(node: JsonNode): string {
  const inner = nonNull(node);
  const rules: string[] = [];
  if (inner.minLength !== undefined && inner.minLength > 0) rules.push(`≥ ${String(inner.minLength)} chars`);
  if (inner.maxLength !== undefined) rules.push(`≤ ${String(inner.maxLength)} chars`);
  if (inner.exclusiveMinimum !== undefined) rules.push(`> ${String(inner.exclusiveMinimum)}`);
  if (inner.minimum !== undefined) rules.push(`≥ ${String(inner.minimum)}`);
  if (inner.maximum !== undefined && inner.maximum < Number.MAX_SAFE_INTEGER) rules.push(`≤ ${String(inner.maximum)}`);
  if (inner.pattern !== undefined) rules.push(`\`${inner.pattern}\``);
  return rules.join(", ");
}

function table(name: string, node: JsonNode): string[] {
  const inner = nonNull(node);
  const object = inner.type === "array" ? nonNull(inner.items ?? {}) : inner;
  const required = new Set(object.required ?? []);
  const lines = [`### \`${name}\``, "", "| Field | Type | Required | Limits | Default |", "|---|---|---|---|---|"];
  for (const [field, child] of Object.entries(object.properties ?? {})) {
    const fallback = child.default !== undefined ? show(child.default) : "";
    lines.push(`| \`${field}\` | ${typeOf(child)} | ${required.has(field) ? "yes" : "no"} | ${ruleOf(child)} | ${fallback} |`);
  }
  return [...lines, ""];
}

/** The whole generated document. Deterministic: same schema, same bytes. */
export function renderSchemaDoc(): string {
  const root = z.toJSONSchema(courseBundleDocSchema, { io: "input", unrepresentable: "any" }) as JsonNode;
  const sections = Object.entries(root.properties ?? {}).filter(([, node]) => nonNull(node).properties ?? nonNull(nonNull(node).items ?? {}).properties);
  return [
    "# Catalog schema",
    "",
    "<!-- Generated by `pnpm schema:generate` from apps/web/src/catalog/domain/schema/. Do not edit; `pnpm schema:check` (gate) fails when it is stale. -->",
    "",
    "One source for every catalog id, slug, label limit and default (CONTRACT.md INV-R1). The bundle validator and the admin",
    "route contracts both derive from `src/catalog/domain/schema/`, so an id the API refuses is refused in a bundle too.",
    "",
    "## Limits",
    "",
    "| Name | Max chars |",
    "|---|---|",
    ...Object.entries(LIMITS).filter(([name]) => name !== "lessonSeconds").map(([name, max]) => `| \`${name}\` | ${String(max)} |`),
    "",
    `A lesson lasts at most ${String(LIMITS.lessonSeconds)} s. A known edition year is ${String(EDITION_YEARS.min)}–${String(EDITION_YEARS.max)}.`,
    "",
    "## Defaults",
    "",
    "| Field | When omitted |",
    "|---|---|",
    ...Object.entries(DEFAULTS).map(([name, value]) => `| \`${name}\` | ${show(value)} |`),
    "",
    "An edition without a year keeps `null` (unknown); a year is never invented. Writing such an edition is refused until",
    "the year is named.",
    "",
    "## CourseBundleV1",
    "",
    `\`version\` is ${show(1)}. Absent or null collections are empty (merge, not deletion).`,
    "",
    ...sections.flatMap(([name, node]) => table(nonNull(node).type === "array" ? `${name}[]` : name, node)),
  ].join("\n");
}

/** Null when `current` is the rendered document, else what to run. */
export function schemaDocProblem(current: string | null): string | null {
  if (current === renderSchemaDoc()) return null;
  return `${SCHEMA_DOC_PATH} is ${current === null ? "missing" : "stale"}; run pnpm schema:generate.`;
}
